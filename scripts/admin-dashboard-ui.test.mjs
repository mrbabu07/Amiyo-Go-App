import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

test("admin dashboard mirrors the reference control-center hierarchy", async () => {
  const dashboard = await readFile(new URL("../apps/mobile/src/features/admin/AdminDashboardScreen.tsx", import.meta.url), "utf8");
  const route = await readFile(new URL("../apps/mobile/app/admin/dashboard.tsx", import.meta.url), "utf8");
  const screen = await readFile(new URL("../apps/mobile/src/ui/Screen.tsx", import.meta.url), "utf8");
  const reportRange = await readFile(new URL("../apps/mobile/src/features/admin/admin-report-range.ts", import.meta.url), "utf8");
  assert.match(route, /AdminDashboardScreen/);
  assert.match(screen, /hideHeading/);
  assert.match(screen, /Admin workspace/);
  assert.match(screen, /Analytics & Reports/);
  assert.match(screen, /Catalog/);
  assert.match(screen, /Customers/);
  assert.match(screen, /Search admin pages/);
  assert.match(screen, /searchResults/);
  assert.match(screen, /onSubmitEditing={submitSearch}/);
  assert.match(screen, /No admin page matches/);
  assert.match(screen, /useAuthStore/);
  assert.match(screen, /session\?\.profile\.displayName/);
  assert.match(screen, /adminRolePriority/);
  assert.doesNotMatch(screen, />Administrator</);
  assert.match(screen, /useThemeStore/);
  assert.match(screen, /toggleTheme/);
  assert.match(screen, /Use dark admin theme/);
  assert.match(screen, /Use light admin theme/);
  assert.match(dashboard, /Amiyo-Go Control Center/);
  assert.match(dashboard, /MARKETPLACE OPERATIONS/);
  assert.match(dashboard, /What needs attention/);
  assert.match(dashboard, /Shop by brand visibility/);
  assert.match(dashboard, /href="\/admin\/cod-delivery"/);
  assert.match(dashboard, /Global order queue/);
  assert.match(dashboard, /Payout and payment desk/);
  assert.match(dashboard, /Exception Handling/);
  assert.match(dashboard, /Returns & refunds/);
  assert.match(dashboard, /Payout review/);
  assert.match(dashboard, /Platform activity/);
  assert.match(dashboard, /!\["CLOSED", "REJECTED"\]\.includes/);
  assert.match(dashboard, /!\["PAID", "REJECTED", "CANCELLED"\]\.includes/);
  assert.match(dashboard, /prioritized without invented SLA or risk scores/);
  assert.match(dashboard, /Custom report start date/);
  assert.match(reportRange, /Custom reports can cover at most 366 days/);
  assert.match(dashboard, /setAnalyticsSelection\(buildCustomAdminRange\(customStart, customEnd\)\)/);
  assert.match(dashboard, /adminSavedViews\.load\(uid\)/);
  assert.match(dashboard, /firebaseAuth\?\.currentUser\?\.uid === uid/);
  assert.match(dashboard, /Saved admin view name/);
  assert.match(dashboard, /Delete saved view/);
  assert.match(dashboard, /ADMIN CONTROL HUB/);
  assert.match(dashboard, /Marketplace Snapshot/);
  assert.match(dashboard, /Reports And Activity/);
  assert.match(dashboard, /Marketplace performance/);
  assert.match(dashboard, /Top vendors/);
  assert.match(dashboard, /Recent platform activity/);
  assert.match(dashboard, /getAdminAnalytics/);
  assert.match(dashboard, /getAdminPlatform/);
  assert.match(dashboard, /getAdminWorkspace/);
  assert.doesNotMatch(dashboard, /#1e7098|#00B14F|#1A1A2E|#7dd3fc|#bae6fd/);
  assert.doesNotMatch(dashboard, /Admin queues.*links\.map/s);
});
